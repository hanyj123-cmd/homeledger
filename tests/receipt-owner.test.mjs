import * as R from '../js/receipts.js';
let n = 0, bad = 0;
const ok = (c, m) => { n++; if (!c) { bad++; console.log('FAIL', m); } };
const acc = (id, type) => ({ account_id: id, name: id, type, is_active: true, currency: 'CAD', subtype: type === 'LIABILITY' ? 'CREDIT_CARD' : '' });
const accMap = new Map([['2010', acc('2010', 'LIABILITY')], ['5010', acc('5010', 'EXPENSE')], ['5020', acc('5020', 'EXPENSE')]]);
const mk = (items, owner) => ({ merchant: 'Costco', date: '2026-10-18', currency: 'CAD', totalText: '60.00', taxText: '0', tipText: '', fromId: '2010', owner: owner || 'Joint', meta: null, items });
const it = (name, amt, cat, owner) => R.newItem({ name, amountText: amt, category_id: cat, tax_code: 'NONE', owner: owner || '' });
const ctx = { accMap, taxCodes: [], rules: [], existing: null, now: 'n' };
let r = R.makeReceiptRecords(mk([it('a', '20', '5010'), it('b', '15', '5010', 'Patrick'), it('c', '25', '5020', 'Ms Kim')]), ctx);
ok(!r.error, 'ok ' + r.error);
const live = r.postings.filter((p) => !p.deleted);
ok(live.length === 4, 'split same category by owner: ' + live.length);
const f = (cat, o) => live.find((p) => p.account_id === cat && (p.owner || 'Joint') === o);
ok(f('5010', 'Joint').amount_cad === 20 && f('5010', 'Patrick').amount_cad === 15 && f('5020', 'Ms Kim').amount_cad === 25, 'amounts by owner');
ok(f('5010', 'Joint').owner === '', 'default owner stored blank on posting');
ok(Math.abs(live.reduce((s, p) => s + p.amount_cad, 0)) < 0.005, 'balanced');
ok(r.txn.owner === 'Joint', 'txn owner default');
ok(r.lineItems.map((l) => l.owner).join() === ',Patrick,Ms Kim', 'line owners');
r = R.makeReceiptRecords(mk([it('a', '35', '5010'), it('b', '25', '5020')]), ctx);
ok(r.postings.filter((p) => !p.deleted).length === 3, 'all default → unchanged shape');
const r3 = R.makeReceiptRecords(mk([it('a', '35', '5010'), it('b', '25', '5010', 'Joint')], 'Patrick'), ctx);
ok(r3.postings.filter((p) => !p.deleted).length === 3 && r3.postings.find((p) => p.owner === 'Joint'), 'explicit differs from receipt default');
const back = R.draftFromExisting(r.txn, { accMap, postings: r.postings, lineItems: r.lineItems, receipt: null });
ok(back.items.length === 2, 'roundtrip');
const r4 = R.makeReceiptRecords(mk([it('a', '20', '5010'), it('b', '15', '5010', 'Patrick'), it('c', '25', '5020', 'Ms Kim')]), { ...ctx });
const back4 = R.draftFromExisting(r4.txn, { accMap, postings: r4.postings, lineItems: r4.lineItems, receipt: null });
ok(back4.items.map((x) => x.owner).join() === ',Patrick,Ms Kim', 'owners survive edit reopen');
const r5 = R.makeReceiptRecords(back4, { ...ctx, existing: { txn: r4.txn, ps: r4.postings, lineItems: r4.lineItems, receipt: null } });
ok(!r5.error && r5.postings.filter((p) => !p.deleted).length === 4, 're-save keeps 4');
console.log(n - bad + '/' + n + ' ok'); process.exit(bad ? 1 : 0);
